package com.tournament.model;

/**
 * Общий контракт для всех сущностей предметной области.
 * <p>
 * Каждая сущность имеет первичный ключ ({@code id}), который назначается
 * репозиторием при сохранении. Интерфейс позволяет хранить разные сущности
 * в одной обобщённой реализации репозитория.
 */
public interface Identifiable {

    Long getId();

    void setId(Long id);
}
