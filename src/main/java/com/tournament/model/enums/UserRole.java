package com.tournament.model.enums;

/**
 * Перечисление ролей пользователей в системе.
 * Используется для разграничения прав доступа к функционалу сервиса.
 */
public enum UserRole {
    ADMIN,    // Администратор - полный доступ к управлению системой
    MANAGER,  // Менеджер - создание и проведение турниров
    REFEREE,  // Судья - внесение результатов матчей
    COACH,    // Тренер - управление составом команды
    CAPTAIN,  // Капитан команды - представление интересов команды на турнире
    PLAYER    // Игрок - участие в соревновани
}