-- Схема базы данных сервиса организации спортивных турниров (PostgreSQL).
--
-- Как использовать в PgAdmin:
--   1. Создать базу данных: CREATE DATABASE tournament_db;
--   2. Выделить tournament_db -> Query Tool -> открыть этот файл -> Execute (F5).
--
-- Скрипт можно выполнять повторно: таблицы создаются через IF NOT EXISTS,
-- внешний ключ users.team_id добавляется только если его ещё нет.
--
-- Примечание: Hibernate также умеет создавать/обновлять таблицы автоматически
-- (spring.jpa.hibernate.ddl-auto=update). Этот файл нужен как наглядная схема
-- и для ручного развёртывания без запуска приложения.
-- Лабораторная работа №4: в password_hash хранится BCrypt-хеш пароля (начинается с $2a$),
-- открытый пароль в базе не сохраняется. Пользователи, созданные до ЛР №4 с паролем
-- в открытом виде, не смогут войти: нужна перезагрузка демо-данных или смена пароля.
-- Пользователи всех ролей хранятся в одной таблице (Single Table Inheritance).
-- Колонка user_type — дискриминатор подкласса (ADMIN, MANAGER, COACH, REFEREE, PLAYER).
-- Колонки phone_number, captain и team_id относятся только к игрокам (PlayerUser),
-- поэтому у остальных ролей они остаются NULL.
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_type     VARCHAR(20)  NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    first_name    VARCHAR(255) NOT NULL,
    last_name     VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    phone_number  VARCHAR(50),
    captain       BOOLEAN,
    team_id       BIGINT
);
-- Спортивные команды. Тренер и капитан — пользователи из таблицы users.
CREATE TABLE IF NOT EXISTS teams (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    city       VARCHAR(255),
    coach_id   BIGINT REFERENCES users (id),
    captain_id BIGINT REFERENCES users (id)
);
-- Внешний ключ игрока на команду добавляется после создания обеих таблиц,
-- так как users.team_id и teams.coach_id/captain_id ссылаются друг на друга.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_users_team'
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT fk_users_team FOREIGN KEY (team_id) REFERENCES teams (id);
    END IF;
END
$$;
-- Турниры. Главный судья — пользователь с ролью REFEREE.
CREATE TABLE IF NOT EXISTS tournaments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(255) NOT NULL,
    sport_type VARCHAR(20),
    start_date DATE,
    end_date   DATE,
    prize_pool NUMERIC(19, 2),
    referee_id BIGINT REFERENCES users (id)
);
-- Связь «многие ко многим»: команды, участвующие в турнире.
CREATE TABLE IF NOT EXISTS tournament_teams (
    tournament_id BIGINT NOT NULL REFERENCES tournaments (id),
    team_id       BIGINT NOT NULL REFERENCES teams (id),
    PRIMARY KEY (tournament_id, team_id)
);
-- Спортивные матчи между двумя командами.
CREATE TABLE IF NOT EXISTS matches (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_team_id  BIGINT NOT NULL REFERENCES teams (id),
    away_team_id  BIGINT NOT NULL REFERENCES teams (id),
    tournament_id BIGINT REFERENCES tournaments (id),
    score         VARCHAR(20) NOT NULL DEFAULT '0:0',
    status        VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    match_date    TIMESTAMP
);
-- Индексы для фильтров, используемых в REST API.
CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);
CREATE INDEX IF NOT EXISTS idx_users_last_name ON users (last_name);
CREATE INDEX IF NOT EXISTS idx_teams_city ON teams (city);
CREATE INDEX IF NOT EXISTS idx_tournaments_sport_type ON tournaments (sport_type);
CREATE INDEX IF NOT EXISTS idx_matches_status ON matches (status);
CREATE INDEX IF NOT EXISTS idx_matches_match_date ON matches (match_date);
